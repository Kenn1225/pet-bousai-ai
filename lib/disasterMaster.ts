/**
 * 既存の回答（川・崖・津波リスク）から、該当しそうな災害を自動で提案する。
 * 地震・停電断水は全国どこでも起こるため常に含める。
 */
export function suggestDisasters(d: {
  riverProximity?: string
  landslideRisk?: string
  tsunamiRisk?: string
}): DisasterType[] {
  const picked: DisasterType[] = ['地震', '停電・断水', '台風']

  if (d.riverProximity === 'すぐそば（500m以内）' || d.riverProximity === '近く（500m〜1km）') {
    picked.push('大雨・洪水')
  }
  if (d.landslideRisk === 'はい（ハザードマップで確認済）' || d.landslideRisk === 'おそらくある') {
    picked.push('土砂災害')
  }
  if (d.tsunamiRisk === 'あり') {
    picked.push('津波', '高潮')
  }
  return picked
}
