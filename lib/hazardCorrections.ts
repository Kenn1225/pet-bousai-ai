/**
 * 沿岸市区町村か判定
 * @param prefecture 都道府県名
 * @param city 市区町村名（null の場合は都道府県レベルで判定、常に false ）
 * @returns true の場合は津波・高潮リスクあり
 */
export function isCoastalCity(prefecture: string, city: string | null = null): boolean {
  if (!city) return false
  const key = `${prefecture}:${city}`
  return COASTAL_CITIES.has(key)
}

